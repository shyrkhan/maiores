from translations import NAMES, TABLES  # noqa: E402 - each other language lives in its own module.

STRINGS.update(TABLES)
# English first, then the others by their own names, as the Preferences list shows them.
LANGUAGES = {"en": "English", **dict(sorted(NAMES.items(), key=lambda item: item[1].casefold()))}
SYSTEM = "system"  # The Preferences choice that follows the computer's language.
RIGHT_TO_LEFT = {"ar"}


def canonical(code):
    """'pt-br', 'PT_BR' and 'pt_BR' are the same language; None when there is no such table."""
    wanted = str(code or "").replace("-", "_").casefold()
    return next((known for known in STRINGS if known.casefold() == wanted), None)


def pick_language(ui_languages):
    """The first of the computer's languages ('de-AT', 'zh-Hant-TW', 'pt-PT') that has a table."""
    for tag in ui_languages:
        parts = str(tag).replace("_", "-").split("-")
        base, rest = parts[0].casefold(), {part.casefold() for part in parts[1:]}
        if base == "zh":
            return "zh_TW" if rest & {"hant", "tw", "hk", "mo"} else "zh_CN" if "zh_CN" in STRINGS else "en"
        if base == "pt" and "pt_BR" in STRINGS:
            return "pt_BR"
        found = canonical(base)
        if found:
            return found
    return "en"


def set_language(code, ui_languages=()):
    """Choose the interface language; "system" follows `ui_languages`. Takes effect for
    everything made afterwards."""
    global LANGUAGE
    LANGUAGE = pick_language(ui_languages) if code == SYSTEM else canonical(code) or "en"


def right_to_left():
    return LANGUAGE in RIGHT_TO_LEFT


def t(key, **values):
    text = STRINGS[LANGUAGE].get(key) or STRINGS["en"][key]
    return text.format(**values) if values else text
